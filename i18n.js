// Orden de ciclo del toggle de idioma
const CPS_LANG_CYCLE = ["en", "es", "de", "ru", "ar", "zh"];

function cpsT(key, lang) {
  return (CPS_I18N[lang] && CPS_I18N[lang][key]) || CPS_I18N.en[key] || key;
}

function cpsNextLang(current) {
  const idx = CPS_LANG_CYCLE.indexOf(current);
  return CPS_LANG_CYCLE[(idx + 1) % CPS_LANG_CYCLE.length];
}

function cpsIsRTL(lang) {
  return CPS_I18N[lang]?.rtl === true;
}
